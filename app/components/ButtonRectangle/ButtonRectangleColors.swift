import SwiftUI

extension Color {

    enum ButtonRectangleColorSet {
        static let icon         = Color("color ButtonRectangle Icon")
        static let iconActive   = Color("color ButtonRectangle Icon Active")
        static let background   = Color("color ButtonRectangle Background")
        static let border       = Color("color ButtonRectangle Border")
        static let borderActive = Color("color ButtonRectangle Border Active")
    }

    static let buttonRectangle = ButtonRectangleColorSet.self

}
